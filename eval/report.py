"""Collect experiment outputs into results/metrics.json and render the README table.

Inputs (written by the experiment scripts; this script never computes metrics):
  eval/benchmark.jsonl, eval/corpus/*         benchmark description
  eval/results/ablation.json                  from eval/ablation.py (required)
  eval/results/judge_agreement.json           from eval/judge_agreement.py (optional;
                                              recorded as pending until labels exist)
  eval/judge/judge_outputs.jsonl, labeling_sheet.csv

Outputs:
  results/metrics.json
  README.md  - the block between the results markers is regenerated from metrics.json.

  python eval/report.py
"""

from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from datetime import date
from pathlib import Path

EVAL_DIR = Path(__file__).resolve().parent
ROOT = EVAL_DIR.parent
METRICS_PATH = ROOT / "results" / "metrics.json"
README_PATH = ROOT / "README.md"
START, END = "<!-- results:start -->", "<!-- results:end -->"


def _jsonl(path: Path) -> list[dict]:
    with path.open(encoding="utf-8") as fh:
        return [json.loads(line) for line in fh]


def collect() -> dict:
    ablation_path = EVAL_DIR / "results" / "ablation.json"
    if not ablation_path.exists():
        sys.exit("eval/results/ablation.json missing - run eval/ablation.py first")
    ablation = json.loads(ablation_path.read_text())

    bench = _jsonl(EVAL_DIR / "benchmark.jsonl")
    sources = json.loads((EVAL_DIR / "corpus" / "sources.json").read_text())
    n_passages = sum(1 for _ in (EVAL_DIR / "corpus" / "passages.jsonl").open())

    judge_outputs = _jsonl(EVAL_DIR / "judge" / "judge_outputs.jsonl")
    with (EVAL_DIR / "judge" / "labeling_sheet.csv").open(newline="", encoding="utf-8") as fh:
        labeled = sum(1 for r in csv.DictReader(fh) if r["faithful"].strip())
    agreement_path = EVAL_DIR / "results" / "judge_agreement.json"
    judge = {
        "items": len(judge_outputs),
        "labeled": labeled,
        "backend": judge_outputs[0]["backend"],
        "judge_score_distribution": {
            variant: {str(k): v for k, v in sorted(
                Counter(r["faithfulness"][variant] for r in judge_outputs).items(),
                key=lambda kv: (kv[0] is None, kv[0]))}
            for variant in judge_outputs[0]["faithfulness"]
        },
    }
    if agreement_path.exists() and labeled == len(judge_outputs):
        judge["status"] = "complete"
        judge["agreement"] = json.loads(agreement_path.read_text())
    else:
        judge["status"] = "pending_manual_labels"

    return {
        "generated": date.today().isoformat(),
        "seed": ablation["meta"].get("seed"),
        "benchmark": {
            "queries": len(bench),
            "query_types": dict(Counter(q["type"] for q in bench)),
            "gold_passages": sum(len(q["gold_ids"]) for q in bench),
            "corpus_documents": len(sources),
            "corpus_passages": n_passages,
            "corpus_source": (
                "Wikipedia (CC BY-SA 4.0), pinned revisions in eval/corpus/sources.json"),
        },
        "retrieval_ablation": ablation,
        "judge_reliability": judge,
    }


def render(metrics: dict) -> str:
    abl = metrics["retrieval_ablation"]
    meta, b = abl["meta"], metrics["benchmark"]
    lines = [
        START,
        "<!-- generated by eval/report.py from results/metrics.json; do not edit by hand -->",
        "",
        f"Retrieval on a {b['queries']}-query benchmark ({b['gold_passages']} gold passages, "
        f"{b['corpus_passages']} passages from {b['corpus_documents']} public documents). "
        f"Latency is retrieval only (no LLM), {meta['device']}, {meta['machine']}, "
        f"seed {metrics['seed']}, measured {meta['date']}.",
        "",
        "| Configuration | Recall@5 [95% CI] | MRR@10 [95% CI] | p50 latency | p95 latency |",
        "|---|---|---|---|---|",
    ]
    for name, r in abl["results"].items():
        lo, hi = r["recall@5_ci"]
        mlo, mhi = r["mrr@10_ci"]
        lines.append(
            f"| {name} | {r['recall@5']:.3f} [{lo:.2f}–{hi:.2f}] "
            f"| {r['mrr@10']:.3f} [{mlo:.2f}–{mhi:.2f}] "
            f"| {r['latency_p50_ms']:.1f} ms | {r['latency_p95_ms']:.1f} ms |"
        )
    j = metrics["judge_reliability"]
    lines.append("")
    if j["status"] == "complete":
        agr = j["agreement"]

        def kappa(r: dict) -> str:
            klo, khi = r["kappa_ci"]
            k = r["kappa"]
            k = "n/a" if k is None or (isinstance(k, float) and k != k) else f"{k:.2f}"
            return f"{k} [{klo:.2f}–{khi:.2f}]"

        lines += ["| LLM-judge reliability | n | Agreement | Cohen's κ [95% CI] | Judge yes-rate |",
                  "|---|---|---|---|---|"]
        for rater, by_variant in agr.get("vs_judge", {"human": agr["variants"]}).items():
            for variant, r in by_variant.items():
                lines.append(f"| {rater} vs judge ({variant}) | {r['n']} | {r['agreement']:.2f} "
                             f"| {kappa(r)} | {r['judge_yes_rate']:.2f} |")
        if agr.get("human_vs_claude"):
            r = agr["human_vs_claude"]
            lines.append(f"| human vs claude (inter-annotator) | {r['n']} "
                         f"| {r['agreement']:.2f} | {kappa(r)} | – |")
        unsure = agr.get("unsure", {}).get("human", [])
        lines += ["", f"Judge: `{j['backend']}`, threshold {agr['threshold']}, "
                      f"{j['items']} answers; {len(unsure)} marked unsure by the human rater "
                      "and excluded from human comparisons. Claude labels were made "
                      "independently before the human labels."]
    else:
        lines.append(f"LLM-judge agreement: **pending** — {j['labeled']}/{j['items']} answers "
                     f"manually labeled (judge: `{j['backend']}`).")
    lines += ["", "Method, caveats and how to reproduce: [eval/README.md](eval/README.md).", END]
    return "\n".join(lines)


def update_readme(block: str) -> None:
    text = README_PATH.read_text(encoding="utf-8")
    if START in text and END in text:
        head, rest = text.split(START, 1)
        _, tail = rest.split(END, 1)
        text = head + block + tail
    else:
        sys.exit(f"README.md has no {START} ... {END} markers")
    README_PATH.write_text(text, encoding="utf-8")


def main() -> None:
    metrics = collect()
    METRICS_PATH.parent.mkdir(exist_ok=True)
    METRICS_PATH.write_text(json.dumps(metrics, indent=2, ensure_ascii=False) + "\n")
    block = render(metrics)
    update_readme(block)
    print(f"wrote {METRICS_PATH.relative_to(ROOT)} and updated README.md\n\n{block}")


if __name__ == "__main__":
    main()
